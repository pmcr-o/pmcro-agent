Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
$root=(Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$plugin='learning-lab';$skill='hello-action';$agent='learning-action-agent'
$dest=Join-Path $root "plugins\$plugin\skills\$skill"
$pluginRoot=Join-Path $root "plugins\$plugin"
if(Test-Path -LiteralPath $dest){throw 'lesson candidate unexpectedly already exists'}
try {
  $creator=Join-Path $root '.pmcro\plugins\skill-creator\skills\create-skill\scripts\create-skill.ps1'
  & $creator -Marketplace $root -Plugin $plugin -Skill $skill -Agent $agent -Description 'A disposable learning action generated by the real skill-creator.' | Out-Null
  foreach($rel in @('SKILL.md',"agents\$agent.md",'scripts\validate.ps1','references\package.md','assets\request.json','tests\fixture.json')){if(-not(Test-Path -LiteralPath (Join-Path $dest $rel) -PathType Leaf)){throw "generated action missing $rel"}}
  & (Join-Path $dest 'scripts\validate.ps1') | Out-Null
  $request=Get-Content -LiteralPath (Join-Path $dest 'assets\request.json') -Raw|ConvertFrom-Json
  if($request.registered -ne $false){throw 'candidate creation must not register authority'}
  $catalog=Get-Content -LiteralPath (Join-Path $root '.agents\catalog.json') -Raw|ConvertFrom-Json
  if(@($catalog.skills|Where-Object {$_.plugin -eq $plugin -and $_.id -eq $skill}).Count -ne 0){throw 'candidate silently entered catalog'}
  'LESSON-PASS generate-action'
} finally {
  if(Test-Path -LiteralPath $pluginRoot){Remove-Item -LiteralPath $pluginRoot -Recurse -Force}
}
